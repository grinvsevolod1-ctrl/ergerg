/**
 * Генерирует полный system prompt с контекстом пользователя
 */
export function buildNexikPrompt(options: {
  mode: 'demo' | 'netnext' | 'client'
  visitorName?: string
  visitorHistory?: string
  businessContext?: string
  previousPromises?: string[]
  emotionalState?: 'positive' | 'neutral' | 'negative' | 'angry'
}): string {
  const { mode, visitorName, visitorHistory, businessContext, previousPromises, emotionalState } = options
  
  let prompt = NEXIK_PERSONA_V3
  
  // Add mode-specific context
  if (mode === 'demo') {
    prompt += '\n\n' + NEXIK_DEMO_CONTEXT
  } else if (mode === 'netnext') {
    prompt += '\n\n' + NETNEXT_CONTEXT
  }
  
  // Add visitor context
  if (visitorName || visitorHistory || businessContext || previousPromises?.length || emotionalState) {
    prompt += '\n\n=== КОНТЕКСТ СОБЕСЕДНИКА ===\n'
    
    if (visitorName) {
      prompt += `Имя: ${visitorName}\n`
    }
    
    if (businessContext) {
      prompt += `Бизнес: ${businessContext}\n`
    }
    
    if (visitorHistory) {
      prompt += `История общения: ${visitorHistory}\n`
    }
    
    if (previousPromises?.length) {
      prompt += `Твои обещания (ВЫПОЛНИ!): ${previousPromises.join(', ')}\n`
    }
    
    if (emotionalState) {
      const states = {
        positive: 'Позитивный, открытый к общению',
        neutral: 'Нейтральный',
        negative: 'Немного недоволен, будь внимательнее',
        angry: 'Злится! Успокой, признай проблему, предложи решение'
      }
      prompt += `Настроение: ${states[emotionalState]}\n`
    }
  }
  
  return prompt
}
